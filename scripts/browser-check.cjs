const { chromium } = require('C:/Users/jmatt/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs = require('fs');
const path = require('path');
(async () => {
  fs.mkdirSync(path.join(__dirname, '../qa'), {recursive: true});
  const browser = await chromium.launch({headless:true, executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const page = await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
  const errors=[];
  page.on('pageerror', error=>errors.push(error.message));
  page.on('response', res=>{if(res.status()>=400 && !res.url().includes('missing-test-page'))errors.push(`${res.status()} ${res.url()}`);});
  const base='http://127.0.0.1:8000';
  const totalPosts=JSON.parse(fs.readFileSync(path.join(__dirname,'../content/posts.json'),'utf8')).length;
  const assert=(value,message)=>{if(!value)throw new Error(message);};
  const overflow=async()=>await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
  await page.goto(base, {waitUntil:'networkidle'});
  assert(!(await overflow()),'Desktop homepage overflows');
  assert(await page.locator('h1').count()===1,'Missing homepage heading');
  await page.screenshot({path:path.join(__dirname,'../qa/home-desktop.png'),fullPage:true});
  await page.locator('summary').first().click();
  assert(await page.locator('details').first().getAttribute('open')!==null,'FAQ did not open');
  await page.goto(base+'/blog/',{waitUntil:'networkidle'});
  assert(await page.locator('[data-article]:visible').count()===totalPosts,'Archive count mismatch');
  await page.locator('[data-filter="Patents"]').click();
  assert(await page.locator('[data-article]:visible').count()>0,'Patent filter empty');
  assert(await page.locator('[data-article]:visible:not([data-topic="Patents"])').count()===0,'Filter contains wrong topics');
  await page.locator('#article-search').fill('zzzzzz');
  assert(await page.locator('#no-results').isVisible(),'Missing empty search state');
  await page.locator('#clear-search').click();
  assert(await page.locator('[data-article]:visible').count()===totalPosts,'Clear filter failed');
  await page.locator('#article-search').fill('copyright');
  const results=await page.locator('[data-article]:visible').count();
  assert(results>0 && results<totalPosts,'Search did not narrow results');
  await page.reload({waitUntil:'networkidle'});
  assert(await page.locator('#article-search').inputValue()==='copyright','Search not restored from URL');
  await page.screenshot({path:path.join(__dirname,'../qa/blog-desktop.png'),fullPage:true});
  await page.goto(base+'/why-the-best-patent-strategy-doesnt-stop-at-allowance/',{waitUntil:'networkidle'});
  assert(await page.locator('.author-box').count()===1,'Author footer missing');
  await page.screenshot({path:path.join(__dirname,'../qa/article-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.goto(base,{waitUntil:'networkidle'});
  assert(!(await overflow()),'Mobile homepage overflows');
  await page.screenshot({path:path.join(__dirname,'../qa/home-mobile.png'),fullPage:true});
  await page.locator('.menu-toggle').click();
  assert(await page.locator('.menu-toggle').getAttribute('aria-expanded')==='true','Menu did not open');
  await page.locator('#navigation a').first().click();
  await page.waitForLoadState('networkidle');
  assert(page.url().includes('/about-me/'),'Mobile navigation failed');
  const routes=['/blog/','/contact/','/about-me/','/practice/patents/','/practice/trademarks/','/practice/copyright/','/practice/technology/','/why-the-best-patent-strategy-doesnt-stop-at-allowance/','/difference-patents-copyrights-trademarks/'];
  for(const route of routes){
    await page.goto(base+route,{waitUntil:'networkidle'});
    assert(!(await overflow()),'Mobile overflow: '+route);
  }
  await page.screenshot({path:path.join(__dirname,'../qa/article-mobile.png'),fullPage:true});
  const missing=await page.goto(base+'/missing-test-page');
  assert(missing.status()===404,'Missing page should return 404');
  await page.goto('file:///'+path.resolve(__dirname,'../dist/blog/index.html').replaceAll('\\','/'),{waitUntil:'networkidle'});
  await page.locator('#article-search').fill('patent');
  assert(await page.locator('[data-article]:visible').count()>0,'File-mode search failed');
  await page.locator('[data-article]:visible').first().click();
  await page.waitForLoadState('load');
  assert(await page.locator('.author-box').count()===1,'File-mode article navigation failed');
  await browser.close();
  assert(errors.length===0,errors.join('\n'));
  console.log('PASS: desktop/mobile layouts, FAQ, mobile menu, search/filter/empty state, URL persistence, 404, file-mode search/navigation, no browser errors.');
})().catch(error=>{console.error(error);process.exit(1);});
